fn check_virtualenv(checks: &mut Vec<HealthCheckRecord>, pass: &mut u32, warn: &mut u32) {
    if let Ok(venv) = std::env::var("VIRTUAL_ENV") {
        let short = Path::new(&venv)
            .file_name()
            .unwrap_or_default()
            .to_string_lossy();
        checks.push(HealthCheckRecord {
            name: "venv".into(),
            status: "ok".into(),
            summary: format!("{short} (active)"),
            details: Vec::new(),
            recommendation: None,
        });
        *pass += 1;
        return;
    }

    if let Ok(env) = std::env::var("CONDA_DEFAULT_ENV") {
        checks.push(HealthCheckRecord {
            name: "venv".into(),
            status: "ok".into(),
            summary: format!("conda: {env}"),
            details: Vec::new(),
            recommendation: None,
        });
        *pass += 1;
        return;
    }

    if Path::new(".venv").is_dir() || Path::new("venv").is_dir() {
        checks.push(HealthCheckRecord {
            name: "venv".into(),
            status: "warning".into(),
            summary: "found but not activated".into(),
            details: Vec::new(),
            recommendation: Some("activate the virtual environment before running Python tasks".into()),
        });
        *warn += 1;
    }
}

fn print_report(report: &HealthReport) {
    let width = report
        .sections
        .iter()
        .flat_map(|section| section.checks.iter())
        .map(|check| check.name.len())
        .max()
        .unwrap_or(0)
        .max(9);

    println!("{}", bold("Environment health check"));
    println!();

    for section in &report.sections {
        if section.checks.is_empty() {
            continue;
        }
        println!("{}", bold(&section.name));
        println!();

        for check in &section.checks {
            let icon = match check.status.as_str() {
                "ok" => green("ok"),
                "warning" => yellow("~~"),
                "error" => red("!!"),
                _ => dim("--"),
            };
            let summary = match check.status.as_str() {
                "warning" => yellow(&check.summary),
                "error" => red(&check.summary),
                _ => dim(&check.summary),
            };

            println!("  {icon} {:<width$}  {summary}", check.name);
            for detail in &check.details {
                println!("    {:<width$}  {}", "", dim(detail));
            }
        }

        println!();
    }

    println!(
        "  {} passed, {} warnings, {} errors",
        green(&report.passed.to_string()),
        yellow(&report.warnings.to_string()),
        if report.errors > 0 {
            red(&report.errors.to_string())
        } else {
            report.errors.to_string()
        },
    );

    let next_steps = collect_next_steps(report);
    if !next_steps.is_empty() {
        println!();
        println!("{}", bold("Next steps"));
        println!();
        for step in next_steps {
            println!("  - {step}");
        }
    }
}

fn collect_next_steps(report: &HealthReport) -> Vec<String> {
    let mut next_steps = Vec::new();

    for section in &report.sections {
        for check in &section.checks {
            if !matches!(check.status.as_str(), "warning" | "error" | "info") {
                continue;
            }
            if let Some(recommendation) = &check.recommendation {
                let label = match check.status.as_str() {
                    "error" => "required",
                    "warning" => "recommended",
                    _ => "optional",
                };
                next_steps.push(format!(
                    "{} {} ({}): {}",
                    section.name, check.name, label, recommendation
                ));
            }
        }
    }

    next_steps
}

fn detect_privilege() -> String {
    if which_exists("sudo") {
        "sudo".into()
    } else if which_exists("doas") {
        "doas".into()
    } else if which_exists("pkexec") {
        "pkexec".into()
    } else {
        "none".into()
    }
}

fn which_exists(cmd: &str) -> bool {
    Command::new("which")
        .arg(cmd)
        .output()
        .is_ok_and(|o| o.status.success())
}

// ── Cage / container detection ──────────────────────────────────────

enum Cage {
    Docker,
    Podman,
    Lxc,
    Wsl,
    Kubernetes,
    Host,
}

fn cage_name(cage: &Cage) -> &'static str {
    match cage {
        Cage::Docker => "docker",
        Cage::Podman => "podman",
        Cage::Lxc => "lxc",
        Cage::Wsl => "wsl",
        Cage::Kubernetes => "kubernetes",
        Cage::Host => "host",
    }
}

fn detect_cage() -> Cage {
    if Path::new("/var/run/secrets/kubernetes.io").exists() {
        return Cage::Kubernetes;
    }
    if Path::new("/.dockerenv").exists() {
        return Cage::Docker;
    }
    if Path::new("/run/.containerenv").exists() {
        return Cage::Podman;
    }
    if let Ok(cgroup) = std::fs::read_to_string("/proc/1/cgroup") {
        let cg = cgroup.to_lowercase();
        if cg.contains("docker") {
            return Cage::Docker;
        }
        if cg.contains("kubepods") {
            return Cage::Kubernetes;
        }
        if cg.contains("lxc") {
            return Cage::Lxc;
        }
    }
    if let Ok(val) = std::env::var("container") {
        return if val == "podman" {
            Cage::Podman
        } else if val == "lxc" {
            Cage::Lxc
        } else {
            Cage::Docker
        };
    }
    if let Ok(version) = std::fs::read_to_string("/proc/version")
        && (version.contains("microsoft") || version.contains("Microsoft"))
    {
        return Cage::Wsl;
    }
    Cage::Host
}

// ── Available shells ────────────────────────────────────────────────

fn detect_shells() -> Vec<String> {
    let Ok(content) = std::fs::read_to_string("/etc/shells") else {
        return Vec::new();
    };

    let mut shells: Vec<String> = content
        .lines()
        .filter(|l| {
            let l = l.trim();
            !l.is_empty() && !l.starts_with('#') && l.starts_with('/')
        })
        .filter_map(|l| {
            Path::new(l.trim())
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
        })
        .collect();

    shells.sort();
    shells.dedup();
    shells
}

